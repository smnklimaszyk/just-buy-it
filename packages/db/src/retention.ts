// Section 7.2: one row per table of the app and ebay_live schemas. The schema tests check that
// every table is listed, every numeric column is marked, and that the worker role may delete from
// exactly the tables marked purgedByWorker.

export type RetentionRule = {
  schema: "app" | "ebay_live" | "auth";
  table: string;
  // ADR 0014: 1 eBay content and raw IDs, 2 derived listing data, 3 operations and config.
  class: 1 | 2 | 3;
  // How long a row lives, in words, as the runbook and the dashboard state it.
  lifetime: string;
  // The column the purge compares with the lifetime, or null when rows are not purged by age.
  purgeKey: string | null;
  // Columns that carry a listing price. In candidate and alert they are set to NULL after
  // priceNullAfterDays.
  priceColumns: readonly string[];
  priceNullAfterDays: number | null;
  // Numeric columns that carry no listing price (counts, config, sizes).
  otherNumericColumns: readonly string[];
  // Who writes the rows: the worker, the ops CLI, the server, web (the admin UI and the sign-in),
  // or both processes (quota tables).
  owner: "worker" | "ops" | "server" | "web" | "shared";
  purgedByWorker: boolean;
};

